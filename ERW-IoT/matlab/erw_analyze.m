function [state, result] = erw_analyze(state, event)
%ERW_ANALYZE Validate a proposed route before updating trusted state.
if isempty(state.pending) || event.event_id ~= state.pending.event_id
    error("ERW:EventOrder", "Event is missing, stale, or out of order.");
end
if ~isequal(event.path(:), state.pending.path(:)) || ...
        event.hop_count ~= state.pending.hop_count || ...
        abs(event.rtt_ms - state.pending.rtt_ms) > 1e-9 || ...
        event.source ~= state.pending.source || ...
        event.root ~= state.pending.root || ...
        event.sim_time_s ~= state.pending.sim_time_s || ...
        event.radio_range_m ~= state.pending.radio_range_m || ...
        ~isequal(size(event.positions_m), size(state.pending.positions_m)) || ...
        any(abs(event.positions_m - state.pending.positions_m) > 1e-9, "all") || ...
        ~isequal(event.parents(:), state.pending.parents(:)) || ...
        numel(event.ranks) ~= numel(state.pending.ranks) || ...
        any(abs(event.ranks(:) - state.pending.ranks(:)) > 1e-9)
    error("ERW:EventChanged", "Telemetry differs from the pending raw event.");
end
path = double(event.path(:)');
n = size(state.positions, 1);
if numel(path) < 2 || path(1) ~= state.source || path(end) ~= state.root || ...
        any(path < 1 | path > n | path ~= fix(path)) || ...
        numel(unique(path)) ~= numel(path) || ...
        event.hop_count ~= numel(path)-1 || ...
        ~isfinite(event.rtt_ms) || event.rtt_ms <= 0
    error("ERW:BadTelemetry", "Invalid packet path or RTT.");
end
edge_lengths = hypot(diff(state.positions(path,1)), diff(state.positions(path,2)));
nonlocal = edge_lengths > state.radio_range_m + state.range_tolerance_m;
minimum_path = erw_shortest_path(state.positions, state.source, state.root, ...
    state.radio_range_m);
minimum_hops = numel(minimum_path)-1;
hop_shortfall = event.hop_count < minimum_hops;
samples = sort(state.baseline_ms_per_hop);
q_index = max(1, ceil(0.05 * numel(samples)));
lower_rtt_ms = max(0, minimum_hops * samples(q_index) - 2);
latency_shortfall = event.rtt_ms < lower_rtt_ms;
alarm = any(nonlocal) || (hop_shortfall && latency_shortfall);
suspect_edges = [path(find(nonlocal))', path(find(nonlocal)+1)']; %#ok<FNDSB>
if isempty(suspect_edges) && hop_shortfall && latency_shortfall
    suspect_edges = [path(1:end-1)', path(2:end)'];
end
old_path = state.trusted_path;
if ~alarm
    state.trusted_path = path;
    state.trusted_parents = event.parents;
    if ~isequal(old_path, path)
        state.baseline_version = state.baseline_version + 1;
        state.baseline_ms_per_hop = event.rtt_ms / event.hop_count;
    else
        state.baseline_ms_per_hop = [state.baseline_ms_per_hop, ...
            event.rtt_ms / event.hop_count];
        state.baseline_ms_per_hop = state.baseline_ms_per_hop(max(1,end-49):end);
    end
end
state.last_analyzed_id = event.event_id;
state.pending = [];
state.pending_truth = false;
result = struct( ...
    "event_id", event.event_id, ...
    "alarm", logical(alarm), ...
    "accepted", ~logical(alarm), ...
    "proposed_path", path, ...
    "trusted_path", state.trusted_path, ...
    "trusted_parents", state.trusted_parents, ...
    "path_changed", ~isequal(old_path, path), ...
    "nonlocal_link", any(nonlocal), ...
    "hop_shortfall", logical(hop_shortfall), ...
    "latency_shortfall", logical(latency_shortfall), ...
    "minimum_physical_hops", minimum_hops, ...
    "lower_rtt_ms", lower_rtt_ms, ...
    "baseline_version", state.baseline_version);
% A cell of pairs preserves the outer edge-list array in JSON for one edge.
result.suspect_edges = num2cell(suspect_edges, 2);
result.suspect_edge_count = size(suspect_edges, 1);
end
